def main() -> int:
    args = parse_args()

    banner("AGENTARENA / WORMSHIELD COMPLETE REPRODUCTION")

    check_python_version()

    missing = missing_dependencies()
    if missing:
        print("Missing Python dependencies:")
        for module_name, package_name in missing:
            print(f"  {module_name}  ->  pip package: {package_name}")

        if args.install_missing:
            install_dependencies(missing)
            missing_after = missing_dependencies()
            if missing_after:
                raise RuntimeError(
                    "Some dependencies are still unavailable after installation: "
                    + ", ".join(module for module, _ in missing_after)
                )
        else:
            print(
                "\nInstall them first, or rerun with --install-missing."
            )
            return 2

    resolved_scripts = validate_required_inputs()

    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    log_dir = ROOT / "Reproduction_Logs" / timestamp
    log_dir.mkdir(parents=True, exist_ok=True)

    dataset_audit = audit_dataset(
        log_dir,
        allow_mismatch=args.allow_dataset_mismatch,
    )

    removed_dirs = []
    if args.fresh:
        banner("CLEANING GENERATED RESULTS")
        removed_dirs = clean_generated_dirs()

    steps = build_steps(args)

    run_summary = {
        "started_at": datetime.now().isoformat(timespec="seconds"),
        "root": str(ROOT),
        "python": sys.version,
        "python_executable": PYTHON,
        "fresh": bool(args.fresh),
        "reuse_features": bool(args.reuse_features),
        "skip_bootstrap": bool(args.skip_bootstrap),
        "removed_generated_dirs": removed_dirs,
        "resolved_scripts": resolved_scripts,
        "dataset_audit": dataset_audit,
        "manual_oracle_validation_run": False,
        "aiworm_official_donkeyrail_notebook_run": False,
        "steps": [],
    }

    summary_path = log_dir / "summary.json"

    for index, step in enumerate(steps, start=1):
        result = run_step(
            index,
            step["name"],
            step["command"],
            log_dir,
            expected_paths=step["expected"],
        )

        run_summary["steps"].append(result)
        summary_path.write_text(
            json.dumps(run_summary, indent=2),
            encoding="utf-8",
        )

        if result["status"] != "success" and not args.continue_on_error:
            run_summary["finished_at"] = datetime.now().isoformat(
                timespec="seconds"
            )
            run_summary["overall_status"] = "failed"
            summary_path.write_text(
                json.dumps(run_summary, indent=2),
                encoding="utf-8",
            )

            banner("REPRODUCTION STOPPED")
            print(f"Failed step: {result['name']}")
            print(f"Log: {result['log']}")
            print(f"Summary: {summary_path}")
            return 1

    failures = [
        result
        for result in run_summary["steps"]
        if result["status"] != "success"
    ]

    run_summary["finished_at"] = datetime.now().isoformat(
        timespec="seconds"
    )
    run_summary["overall_status"] = (
        "success"
        if not failures
        else "completed_with_failures"
    )

    summary_path.write_text(
        json.dumps(run_summary, indent=2),
        encoding="utf-8",
    )

    banner("REPRODUCTION FINISHED")

    print(f"Overall status: {run_summary['overall_status']}")
    print(f"Run logs: {log_dir}")
    print(f"Summary JSON: {summary_path}")

    print("\nMain result locations:")
    result_locations = [
        ROOT / "WormShield_Learned_Payload_Results",
        ROOT / "DonkeyRail_AgentArena_Matched_Splits_Results",
        ROOT / "WormShield_Leave_One_Task_Out",
        ROOT / "WormShield_Semantic_Relation_Ablation",
        ROOT / "WormShield_Run_Bootstrap_CI",
        ROOT / "AgentArena_Containment_Replay_Results",
        ROOT / "AgentArena_Threat_Scaling_Results",
    ]
    for p in result_locations:
        if p.exists():
            print(f"  {p}")

    print(
        "\nReminder: this runner intentionally does not perform the manual "
        "45-case oracle validation or the original DonkeyRail AI-Worm "
        "notebook evaluation."
    )

    return 0 if not failures else 1


