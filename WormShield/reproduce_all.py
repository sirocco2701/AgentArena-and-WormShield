def banner(text: str) -> None:
    print("\n" + "=" * 100)
    print(text)
    print("=" * 100)


def resolve_script(key: str) -> Path:
    for name in SCRIPT_CANDIDATES[key]:
        p = ROOT / name
        if p.exists():
            return p

    if key == "transformation":
        matches = sorted(ROOT.glob("wormshield*transformation*robustness*.py"))
        if matches:
            return matches[0]

    raise FileNotFoundError(
        f"Could not find script for '{key}'. Tried: "
        + ", ".join(SCRIPT_CANDIDATES[key])
    )


def check_python_version() -> None:
    if sys.version_info < (3, 10):
        raise RuntimeError(
            f"Python 3.10+ is required. Current version: {sys.version}"
        )


def missing_dependencies() -> list[tuple[str, str]]:
    missing = []
    for module_name, package_name in DEPENDENCIES.items():
        try:
            importlib.import_module(module_name)
        except Exception:
            missing.append((module_name, package_name))
    return missing


def install_dependencies(missing: list[tuple[str, str]]) -> None:
    packages = sorted({package for _, package in missing})
    if not packages:
        return
    print("Installing missing packages:")
    print("  " + " ".join(packages))
    subprocess.run(
        [PYTHON, "-m", "pip", "install", *packages],
        cwd=ROOT,
        check=True,
    )


def validate_required_inputs() -> dict[str, str]:
    required_root_files = [
        ROOT / "wormshield-observable-main.csv",
        ROOT / "wormshield_learned_payload.py",
    ]

    for p in required_root_files:
        if not p.exists():
            raise FileNotFoundError(f"Missing required input: {p.name}")

    for rel in AIWORM_REQUIRED:
        p = ROOT / rel
        if not p.exists():
            raise FileNotFoundError(
                "Missing AI-Worm benchmark file:\n"
                f"  {p}\n"
                "Check the donkeyrail-test folder structure."
            )

    resolved = {}
    for key in SCRIPT_CANDIDATES:
        resolved[key] = str(resolve_script(key).name)

    containment_path = resolve_script("containment")
    containment_text = containment_path.read_text(
        encoding="utf-8",
        errors="ignore",
    )
    required_markers = [
        "run_metrics.csv",
        "containment_table.csv",
        "replay_audit.csv",
    ]
    missing_markers = [
        marker
        for marker in required_markers
        if marker not in containment_text
    ]
    if missing_markers:
        raise RuntimeError(
            f"{containment_path.name} does not look like the full replay script. "
            f"Missing markers: {missing_markers}. "
            "Use the full v3 containment replay file."
        )

    return resolved


def audit_dataset(log_dir: Path, allow_mismatch: bool) -> dict:
    import pandas as pd

    path = ROOT / "wormshield-observable-main.csv"
    df = pd.read_csv(path)

    required_columns = {
        "run_id",
        "label_binary",
        "label_multiclass",
    }
    missing_columns = sorted(required_columns.difference(df.columns))
    if missing_columns:
        raise ValueError(
            f"Dataset is missing required columns: {missing_columns}"
        )

    label_counts = (
        df["label_multiclass"]
        .fillna("")
        .astype(str)
        .str.strip()
        .str.lower()
        .value_counts()
        .to_dict()
    )

    binary_counts = (
        pd.to_numeric(
            df["label_binary"],
            errors="raise",
        )
        .astype(int)
        .value_counts()
        .sort_index()
        .to_dict()
    )

    audit = {
        "dataset": str(path),
        "rows": int(len(df)),
        "unique_runs": int(df["run_id"].astype(str).nunique()),
        "label_multiclass_counts": {
            str(k): int(v)
            for k, v in label_counts.items()
        },
        "label_binary_counts": {
            str(k): int(v)
            for k, v in binary_counts.items()
        },
        "expected": {
            "rows": EXPECTED_ROWS,
            "unique_runs": EXPECTED_RUNS,
            "label_multiclass_counts": EXPECTED_LABELS,
            "label_binary_counts": {
                str(k): v
                for k, v in EXPECTED_BINARY.items()
            },
        },
    }

    problems = []

    if len(df) != EXPECTED_ROWS:
        problems.append(
            f"rows={len(df)} expected={EXPECTED_ROWS}"
        )

    run_count = int(df["run_id"].astype(str).nunique())
    if run_count != EXPECTED_RUNS:
        problems.append(
            f"runs={run_count} expected={EXPECTED_RUNS}"
        )

    for label, expected in EXPECTED_LABELS.items():
        actual = int(label_counts.get(label, 0))
        if actual != expected:
            problems.append(
                f"{label}={actual} expected={expected}"
            )

    for label, expected in EXPECTED_BINARY.items():
        actual = int(binary_counts.get(label, 0))
        if actual != expected:
            problems.append(
                f"binary_{label}={actual} expected={expected}"
            )

    audit["matches_current_paper"] = not problems
    audit["problems"] = problems

    audit_path = log_dir / "dataset_audit.json"
    audit_path.write_text(
        json.dumps(audit, indent=2),
        encoding="utf-8",
    )

    print("\nDataset audit:")
    print(f"  rows: {audit['rows']}")
    print(f"  runs: {audit['unique_runs']}")
    print(f"  labels: {audit['label_multiclass_counts']}")
    print(f"  binary: {audit['label_binary_counts']}")

    if problems:
        print("\nDataset does not match the current paper:")
        for problem in problems:
            print(f"  {problem}")

        if not allow_mismatch:
            raise RuntimeError(
                "Dataset audit failed. "
                "Use --allow-dataset-mismatch only if this difference is intentional."
            )
    else:
        print("  status: matches current paper counts")

    return audit


def clean_generated_dirs() -> list[str]:
    removed = []
    for name in GENERATED_DIRS:
        p = ROOT / name
        if p.exists():
            print(f"Removing generated folder: {p}")
            shutil.rmtree(p)
            removed.append(name)
    return removed


def ensure_expected(paths: Iterable[Path]) -> list[str]:
    missing = []
    for p in paths:
        if not p.exists():
            missing.append(str(p))
    return missing


def run_step(
    number: int,
    name: str,
    command: list[str],
    log_dir: Path,
    expected_paths: Iterable[Path] = (),
) -> dict:
    banner(f"STEP {number}: {name}")
    print("Command:")
    print("  " + " ".join(f'"{x}"' if " " in x else x for x in command))

    slug = "".join(
        c.lower() if c.isalnum() else "_"
        for c in name
    ).strip("_")
    log_path = log_dir / f"{number:02d}_{slug}.log"

    env = os.environ.copy()
    env["PYTHONUNBUFFERED"] = "1"
    env["PYTHONIOENCODING"] = "utf-8"

    start = time.time()

    with log_path.open("w", encoding="utf-8") as log:
        log.write("COMMAND\n")
        log.write(" ".join(command) + "\n\n")
        log.flush()

        process = subprocess.Popen(
            command,
            cwd=ROOT,
            env=env,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            encoding="utf-8",
            errors="replace",
            bufsize=1,
        )

        assert process.stdout is not None

        for line in process.stdout:
            print(line, end="")
            log.write(line)
            log.flush()

        return_code = process.wait()

    elapsed = time.time() - start

    expected_paths = list(expected_paths)
    missing_outputs = ensure_expected(expected_paths)

    result = {
        "step": number,
        "name": name,
        "command": command,
        "return_code": int(return_code),
        "seconds": round(elapsed, 3),
        "log": str(log_path),
        "expected_outputs": [str(p) for p in expected_paths],
        "missing_expected_outputs": missing_outputs,
        "status": (
            "success"
            if return_code == 0 and not missing_outputs
            else "failed"
        ),
    }

    if return_code != 0:
        print(
            f"\nFAILED: {name} returned code {return_code}. "
            f"See {log_path}"
        )
    elif missing_outputs:
        print("\nFAILED: command completed but expected outputs are missing:")
        for p in missing_outputs:
            print(f"  {p}")
    else:
        print(f"\nCompleted in {elapsed / 60.0:.2f} minutes.")

    return result


